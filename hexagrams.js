// 원문은 "제목구, 같은 뜻의 설명 괘입니다. 조언" 형태라 앞부분이 뒷문장과 중복되었다.
const KEYWORD_FIX = {
  '101101': '밝음과 의지',
  '011110': '대들보가 휠 만큼 무거운 짐',
  '001100': '작은 일은 가능하나 큰일은 무리',
  '101010': '일이 이루어지고 질서가 잡힘'
};
Object.keys(HEXAGRAMS).forEach(key => {
  const h = HEXAGRAMS[key];
  const meta = HEX_META_BY_BITS[key];
  h.n = meta.n;
  h.name = meta.ko + ' (' + meta.han + ')';
  const m = h.summary.match(/^([^,]+?), (.+괘입니다\..*)$/);
  if (m) { h.keyword = m[1]; h.summary = m[2]; }
  else { h.keyword = KEYWORD_FIX[key] || h.name; }
});

